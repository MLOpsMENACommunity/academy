import { z } from 'zod';
import { emailSchema } from './auth';
import { LOCALES } from './enums';

/**
 * Joining a course's waiting list. Signed-in students send nothing (their account
 * email is used); visitors send an email. `website` is a honeypot: people never see
 * it, so a filled-in value means a bot.
 */
export const courseInterestSchema = z.object({
  email: emailSchema.optional(),
  locale: z.enum(LOCALES).optional(),
  website: z.string().max(200).optional(),
});
export type CourseInterestInput = z.infer<typeof courseInterestSchema>;

/** The signed link in every waiting-list email: `<id>.<signature>`. */
export const waitlistTokenSchema = z.object({ token: z.string().regex(/^[a-z0-9]{10,40}\.[\w-]{20,64}$/) });

export interface CourseInterestResult {
  /** Always true: joining twice is not an error. */
  joined: true;
}

export interface WaitlistLeaveResult {
  left: boolean;
  /** The course the link was for (when the entry still existed). */
  course: { slug: string; titleEn: string; titleAr: string } | null;
}

/** One row of the admin's waiting-list tab. */
export interface WaitlistEntryDto {
  id: string;
  email: string;
  name: string | null;
  /** Has an academy account (joined while signed in). */
  student: boolean;
  locale: 'en' | 'ar';
  joinedAt: string;
  notifiedAt: string | null;
  delivery: 'PENDING' | 'SENT' | 'FAILED' | 'SKIPPED' | null;
}

export interface WaitlistDto {
  count: number;
  /** Not notified yet and not being notified right now. */
  waiting: number;
  notified: number;
  sending: number;
  entries: WaitlistEntryDto[];
}

/** "The course is open" message to everyone on the waiting list who hasn't been told yet. */
export const waitlistNotifySchema = z.object({
  subjectEn: z.string().trim().min(2).max(150),
  subjectAr: z.string().trim().max(150).default(''),
  bodyEn: z.string().trim().min(2).max(5000),
  bodyAr: z.string().trim().max(5000).default(''),
  /** Generated by the client per send: a retried request can't send twice. */
  idempotencyKey: z.string().regex(/^[\w-]{16,64}$/),
});
export type WaitlistNotifyInput = z.infer<typeof waitlistNotifySchema>;
