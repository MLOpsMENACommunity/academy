import { z } from 'zod';
import type { CourseStatus } from './enums';

/**
 * Speakers send announcements: to the enrolled students of a course an admin assigned them to
 * (they're one of its instructors), or to the registrants of a live session they speak at,
 * host or guest. They go out at once (no approval), so they're short and rate-limited.
 */

/** At most this many announcements per course or session, per speaker, in any 24 hours. */
export const SPEAKER_ANNOUNCEMENTS_PER_TARGET_PER_DAY = 5;
/** At most this many announcements per speaker, in any 24 hours. */
export const SPEAKER_ANNOUNCEMENTS_PER_DAY = 20;
/** A session stays reachable for this long after it starts (follow-ups: slides, recording). */
export const SPEAKER_SESSION_ANNOUNCE_DAYS = 30;
export const SPEAKER_ANNOUNCEMENT_SUBJECT_MAX = 120;
export const SPEAKER_ANNOUNCEMENT_BODY_MAX = 3000;

/** Control characters (except tab and newline) and bidi overrides never reach an email or the page. */
// eslint-disable-next-line no-control-regex
const CONTROL = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F\u202A-\u202E\u2066-\u2069]/g;
const clean = (v: string) => v.replace(/\r\n?/g, '\n').replace(CONTROL, '').trim();
const subject = (min: number) => z.string().transform(clean).pipe(z.string().min(min).max(SPEAKER_ANNOUNCEMENT_SUBJECT_MAX));
const body = (min: number) =>
  z
    .string()
    .transform((v) => clean(v).replace(/\n{3,}/g, '\n\n'))
    .pipe(z.string().min(min).max(SPEAKER_ANNOUNCEMENT_BODY_MAX));

/** A speaker's announcement. Plain text (links become clickable); Arabic falls back to English. */
export const speakerAnnouncementSchema = z.object({
  subjectEn: subject(2),
  subjectAr: subject(0).default(''),
  bodyEn: body(2),
  bodyAr: body(0).default(''),
  /** Generated by the client per message: a retried request can't send twice. */
  idempotencyKey: z.string().regex(/^[\w-]{16,64}$/),
});
export type SpeakerAnnouncementInput = z.infer<typeof speakerAnnouncementSchema>;

export type SpeakerAnnouncementTargetKind = 'course' | 'session';

export interface SpeakerCourseTargetDto {
  id: string;
  slug: string;
  titleEn: string;
  titleAr: string;
  status: CourseStatus;
  /** How many enrolled students would receive it. A number only, never who. */
  audience: number;
  /** Sent to this course in the last 24 hours. */
  sentToday: number;
}

export interface SpeakerSessionTargetDto {
  id: string;
  slug: string;
  titleEn: string;
  titleAr: string;
  startsAt: string;
  role: 'SPEAKER' | 'HOST' | 'GUEST';
  /** How many people are registered. A number only, never who. */
  audience: number;
  sentToday: number;
}

export interface SpeakerSentAnnouncementDto {
  id: string;
  at: string;
  kind: SpeakerAnnouncementTargetKind;
  targetId: string;
  targetTitleEn: string;
  targetTitleAr: string;
  subjectEn: string;
  subjectAr: string;
  recipients: number;
  sent: number;
  pending: number;
  failed: number;
}

export interface SpeakerAnnouncementsDto {
  /** False when the account has no public speaker profile yet (nothing to assign). */
  hasProfile: boolean;
  courses: SpeakerCourseTargetDto[];
  sessions: SpeakerSessionTargetDto[];
  sent: SpeakerSentAnnouncementDto[];
  limits: { perTargetPerDay: number; perDay: number; sentToday: number };
}

/** Admin → Speakers → {speaker} → Assigned courses. */
export interface AssignedCourseDto {
  id: string;
  slug: string;
  titleEn: string;
  titleAr: string;
  status: CourseStatus;
}

export interface SpeakerAssignmentsDto {
  /** The speaker account behind the profile, if any: without one, nobody can send as them. */
  account: { email: string; role: string; active: boolean } | null;
  assigned: AssignedCourseDto[];
  /** Courses that can be assigned (any status except archived), minus the assigned ones. */
  available: AssignedCourseDto[];
}
